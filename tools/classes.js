  "نوف المطيري":{"ابتدائي":"معلمة جديدة"}, "شهد المطيري":{"ابتدائي":"معلمة جديدة"},
  "عبير البريدي":{"ابتدائي":"معلمة متميزة","متوسط":"معلمة خبرة"}, "ورود البطيح":{"ابتدائي":"معلمة خبرة"},
